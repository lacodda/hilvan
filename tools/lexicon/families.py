"""Builds the word families of the English lexicon: which of its lemmas are
made from one another - decide, decision, decisive.

    python tools/lexicon/families.py     # writes lexicons/en/families.tsv

Reads lexicons/en/lexicon.tsv for the lemmas and their ranks, and the Open
English WordNet, downloaded once into tools/lexicon/.cache, for which words
are derived from which. Needs nothing beyond the standard library.
"""

from __future__ import annotations

import argparse
import collections
import gzip
import pathlib
import sys
import urllib.request
import xml.etree.ElementTree as ET

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
CACHE = HERE / ".cache"

OEWN_EDITION = "2025"
OEWN_URL = f"https://github.com/globalwordnet/english-wordnet/releases/download/{OEWN_EDITION}-edition/english-wordnet-{OEWN_EDITION}.xml.gz"

# The links of the wordnet that say one word is made from another: a noun from
# a verb (decide - decision), an adverb from an adjective (happy - happily),
# an adjective from a verb's participle.
RELATIONS = {"derivation", "pertainym", "participle"}

# How much of the start of a word two lemmas have to share to be one family.
# The wordnet also links words by meaning alone - "urban" pertains to "city",
# "death" is made from "die" - and a learner does not see a family there:
# a family is a word the learner can read off another. Four letters, or the
# whole of the shorter word: "act" and "action".
SHARED = 4

HEADER = """\
# Word families of the English lexicon: lemmas made from one another.
#
# head <TAB> the other members, space-separated
#
# The head is the commonest member; every member is a lemma of lexicon.tsv,
# and each lemma is in one family at most. Generated by
# tools/lexicon/families.py - do not edit by hand. Built from:
#   lexicon.tsv, beside this file - CC BY-SA 4.0
#   Open English WordNet {edition} (globalwordnet), which word is derived from which - CC BY 4.0
#
# This file is licensed CC BY-SA 4.0. See lexicons/en/README.md.
"""


def fetch(url: str, name: str) -> pathlib.Path:
    CACHE.mkdir(exist_ok=True)
    path = CACHE / name
    if not path.exists():
        print(f"downloading {url}", file=sys.stderr)
        with urllib.request.urlopen(url) as response:
            path.write_bytes(response.read())
    return path


def read_lexicon(path: pathlib.Path) -> tuple[dict[str, tuple[int, str]], dict[str, set[str]]]:
    """Lemmas by their lowercase key, with rank and spelling, and the forms
    each one takes."""
    lemmas: dict[str, tuple[int, str]] = {}
    forms: dict[str, set[str]] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        rank, lemma, _ipa, spellings = line.split("\t")
        key = lemma.lower()
        lemmas[key] = (int(rank), lemma)
        forms[key] = set(spellings.split())
    return lemmas, forms


def read_links(path: pathlib.Path) -> list[tuple[str, str]]:
    """Every pair of written forms the wordnet derives one from the other."""
    sense_lemma: dict[str, str] = {}
    pending: list[tuple[str, str]] = []
    lemma = ""
    with gzip.open(path) as stream:
        for event, element in ET.iterparse(stream, events=("start", "end")):
            if event == "start" and element.tag == "Lemma":
                lemma = element.get("writtenForm", "")
            elif event == "end" and element.tag == "Sense":
                sense_lemma[element.get("id", "")] = lemma
                for relation in element.findall("SenseRelation"):
                    if relation.get("relType") in RELATIONS:
                        pending.append((lemma, relation.get("target", "")))
            elif event == "end" and element.tag == "LexicalEntry":
                element.clear()
    links = []
    for written, target in pending:
        other = sense_lemma.get(target)
        if other:
            links.append((written.lower(), other.lower()))
    return links


def related(a: str, b: str, forms: dict[str, set[str]]) -> bool:
    """Whether a learner can read one of two derived words off the other:
    they begin alike, or one is a spelling of the other ("dying")."""
    if b in forms.get(a, set()) or a in forms.get(b, set()):
        return True
    shared = 0
    for x, y in zip(a, b):
        if x != y:
            break
        shared += 1
    return shared >= min(SHARED, len(a), len(b))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--lexicon", default=str(ROOT / "lexicons/en/lexicon.tsv"))
    parser.add_argument("--out", default=str(ROOT / "lexicons/en/families.tsv"))
    args = parser.parse_args()

    lemmas, forms = read_lexicon(pathlib.Path(args.lexicon))
    links = read_links(fetch(OEWN_URL, f"english-wordnet-{OEWN_EDITION}.xml.gz"))

    edges: dict[str, set[str]] = collections.defaultdict(set)
    for a, b in links:
        if a != b and a in lemmas and b in lemmas and related(a, b, forms):
            edges[a].add(b)
            edges[b].add(a)

    # A family is everything linked to everything else through such pairs.
    seen: set[str] = set()
    families: list[list[str]] = []
    for start in sorted(edges):
        if start in seen:
            continue
        seen.add(start)
        stack, members = [start], []
        while stack:
            lemma = stack.pop()
            members.append(lemma)
            for other in edges[lemma]:
                if other not in seen:
                    seen.add(other)
                    stack.append(other)
        families.append(sorted(members, key=lambda key: (lemmas[key][0], key)))
    families.sort(key=lambda members: lemmas[members[0]][0])

    out = pathlib.Path(args.out)
    with out.open("w", encoding="utf-8", newline="\n") as file:
        file.write(HEADER.format(edition=OEWN_EDITION))
        for members in families:
            head, *rest = (lemmas[key][1] for key in members)
            file.write(f"{head}\t{' '.join(rest)}\n")
    held = sum(len(members) for members in families)
    print(f"wrote {len(families)} families of {held} lemmas to {out}", file=sys.stderr)


if __name__ == "__main__":
    main()
